function highlight() {
  const words = document.querySelectorAll("strong");
  words.forEach(function (word) {
    word.style.color = "rgb(0, 128, 0)";
  });
}

function return_normal() {
  const words = document.querySelectorAll("strong");
  words.forEach(function (word) {
    word.style.color = "rgb(0, 0, 0)";
  });
}


